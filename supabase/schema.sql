-- 5. Finanças e Quotas
create table if not exists public.financial_accounts (
  id integer generated by default as identity primary key,
  scope text not null check (scope in ('NACIONAL', 'PROVINCIAL')),
  province_id integer references public.provinces(id),
  name text not null,
  balance_aoa numeric(14,2) not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.quotas (
  id integer generated by default as identity primary key,
  member_id integer not null references public.members(id),
  province_id integer not null references public.provinces(id),
  reference_month text not null,
  amount_aoa numeric(14,2) not null,
  status text not null default 'PAGO' check (status in ('PAGO', 'PENDENTE', 'EM_ATRASO')),
  paid_at text,
  receipt_number text unique,
  recorded_by integer references public.users(id),
  created_at timestamptz not null default now(),
  unique(member_id, reference_month)
);

create table if not exists public.financial_transactions (
  id integer generated by default as identity primary key,
  account_id integer not null references public.financial_accounts(id),
  province_id integer references public.provinces(id),
