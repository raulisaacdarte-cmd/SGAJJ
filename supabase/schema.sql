-- Políticas públicas estritas (apenas catálogos e conteúdos explicitamente publicados)
drop policy if exists "public_read_provinces" on public.provinces;
create policy "public_read_provinces" on public.provinces
  for select using (is_active = 1);

drop policy if exists "public_read_municipalities" on public.municipalities;
create policy "public_read_municipalities" on public.municipalities
  for select using (true);

drop policy if exists "public_read_categories" on public.member_categories;
create policy "public_read_categories" on public.member_categories
  for select using (true);

drop policy if exists "public_read_departments" on public.departments;
create policy "public_read_departments" on public.departments
  for select using (true);

drop policy if exists "public_read_roles" on public.roles;
create policy "public_read_roles" on public.roles
  for select using (true);

drop policy if exists "public_read_published_publications" on public.publications;
create policy "public_read_published_publications" on public.publications
  for select using (status = 'PUBLICADO');

drop policy if exists "public_read_approved_activities" on public.activities;
create policy "public_read_approved_activities" on public.activities
  for select using (approval_status = 'APROVADA');

drop policy if exists "authenticated_read_own_member" on public.members;
create policy "authenticated_read_own_member" on public.members
  for select to authenticated using (lower(email) = lower(auth.jwt() ->> 'email'));

drop policy if exists "authenticated_read_own_application" on public.applications;
create policy "authenticated_read_own_application" on public.applications
  for select to authenticated using (lower(email) = lower(auth.jwt() ->> 'email'));
