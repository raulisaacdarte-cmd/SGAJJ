-- SGAJJ — Plataforma Nacional de Gestão da Associação de Jovens Juristas (Angola)
-- Schema PostgreSQL completo para Supabase com Row Level Security (RLS) e Storage Bucket

create extension if not exists pgcrypto;

-- 1. Configurações institucionais
create table if not exists public.system_settings (
  id integer primary key check (id = 1),
  acronym text not null default 'SGAJJ',
  organization_name text not null default 'Associação de Jovens Juristas',
  slogan text not null default 'Juntos em prol do bem maior.',
  logo_path text not null default '/assets/aistudio/IMG-20260804-WA0073_3cc94a37.jpg',
  nif text default '',
  headquarters_address text default 'Luanda, República de Angola',
  contact_email text default 'associacaodejovensjuristas@gmail.com',
  contact_phone text default '',
  institutional_iban text default '0040 0000 96614389101 60',
  privacy_policy text not null default '',
  setup_completed integer not null default 0,
  auto_backup_enabled integer not null default 1,
  last_backup_at text,
  updated_at timestamptz not null default now()
);

-- 2. Catálogos territoriais e estatutários
create table if not exists public.provinces (
  id integer generated by default as identity primary key,
  code text not null unique,
  name text not null unique,
  is_active integer not null default 1
);

create table if not exists public.municipalities (
  id integer generated by default as identity primary key,
  province_id integer not null references public.provinces(id) on delete cascade,
  name text not null,
  unique(province_id, name)
);

create table if not exists public.departments (
  id integer generated by default as identity primary key,
  code text not null unique,
  name text not null,
  description text default ''
);

create table if not exists public.roles (
  code text primary key,
  name text not null,
  scope text not null check (scope in ('NATIONAL', 'PROVINCIAL', 'MEMBER')),
  rank integer not null,
  department_code text references public.departments(code)
);

create table if not exists public.member_categories (
  id integer generated by default as identity primary key,
  code text not null unique,
  name text not null,
  monthly_quota_aoa numeric(14,2) not null default 0,
  description text default ''
);

-- 3. Associados e Perfis Institucionais (sem hashes de credenciais)
create table if not exists public.members (
  id integer generated by default as identity primary key,
  member_code text not null unique,
  full_name text not null,
  birth_date text,
  phone text not null,
  email text not null unique,
  province_id integer not null references public.provinces(id),
  municipality_id integer references public.municipalities(id),
  institution text default '',
  academic_degree text default '',
  category_id integer not null references public.member_categories(id),
  photo_path text,
  status text not null default 'ATIVO' check (status in ('ATIVO', 'SUSPENSO', 'INATIVO', 'EXONERADO')),
  joined_at text not null default (current_date::text),
  documents_json text not null default '[]',
  participation_history_json text not null default '[]',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.users (
  id integer generated by default as identity primary key,
  email text not null unique,
  phone text not null default '',
  full_name text not null,
  role_code text not null references public.roles(code),
  province_id integer references public.provinces(id),
  department_id integer references public.departments(id),
  member_id integer references public.members(id),
  photo_path text,
  activation_pending integer not null default 0,
  mfa_enabled integer not null default 0,
  is_active integer not null default 1,
  consent_lgpd integer not null default 1,
  last_login_at text,
  created_at timestamptz not null default now()
);

