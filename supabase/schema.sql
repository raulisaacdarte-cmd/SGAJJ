  category text not null,
  description text not null,
  amount_aoa numeric(14,2) not null,
  reference_date text not null default (current_date::text),
  receipt_number text unique,
  status text not null default 'APROVADO' check (status in ('PENDENTE_APROVACAO', 'APROVADO', 'REJEITADO', 'ANULADO')),
  approved_by integer references public.users(id),
  approved_at text,
  attachment_path text,
  bank_code text default '',
  rupe_code text default '',
  payment_channel text default '',
  member_id integer references public.members(id),
  created_by integer references public.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.quota_rupes (
